def _catalog() -> dict[str, tuple[str, str]]:
    catalog = {}
    for stage, reason, suites in GROUPS:
        for prefix, names in suites.items():
            for name in names.split():
                case = f"{prefix}.{name}"
                if case in catalog:
                    raise ValueError(f"conflicting execution policies for {case}")
                catalog[case] = (stage, reason)
    return catalog


CATALOG = _catalog()


def policy(case: str | None, suite: str | None, disruptive: str | None) -> tuple[str, str]:
    stage, reason = CATALOG.get(case, ("exclusive", "No reviewed execution policy"))
    if stage == "eligible" and (
        disruptive or suite in {"cache", "fleet", "long_context", "real_clients", "scenarios"}
    ):
        raise ValueError(f"{case}: concurrent execution conflicts with exclusive case requirements")
    if disruptive:
        reason = disruptive
    return stage, reason
